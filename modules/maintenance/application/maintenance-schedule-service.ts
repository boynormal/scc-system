import type { PrismaClient } from "@prisma/client"
import { z } from "zod"
import type { UserRole } from "@/lib/permissions"
import { permissionCoversBranch } from "@/shared/permissions/branch-sharing"
import { readableBranchIds } from "@/modules/maintenance/application/branch-scope"
import {
  generatePmForPlan,
  generatePreventiveWork,
  parseDateOnly,
} from "@/modules/maintenance/application/pm-generator"
import {
  targetAssetSelect,
  targetBranchId,
  targetInactiveReason,
  targetMachineSelect,
  targetScopeWhere,
} from "@/modules/maintenance/application/pm-target"

export const createMaintenanceScheduleSchema = z.object({
  planId: z.string().uuid(),
  dueDate: z.string(),
  isAutoGenerated: z.boolean().optional(),
})

export type CreateMaintenanceScheduleInput = z.infer<typeof createMaintenanceScheduleSchema>

export async function listMaintenanceSchedules(
  db: PrismaClient,
  params: {
    companyId: string
    roles: UserRole[]
    branchId?: string | null
    status?: string | null
    machineId?: string | null
    assetId?: string | null
    dateFrom?: string | null
    dateTo?: string | null
    page: number
    pageSize: number
  }
) {
  const scope = readableBranchIds(params.roles, "schedules")
  if (scope !== "all" && scope.length === 0) {
    return { data: [], total: 0, page: params.page, pageSize: params.pageSize, totalPages: 0 }
  }
  if (params.branchId && scope !== "all" && !scope.includes(params.branchId)) {
    return { error: "Forbidden" as const, status: 403 as const }
  }
  const where = {
    AND: [targetScopeWhere(params.companyId, params.branchId ? [params.branchId] : scope)],
    ...(params.machineId && { machineId: params.machineId }),
    ...(params.assetId && { assetId: params.assetId }),
    ...(params.status && { status: params.status as never }),
    ...(params.dateFrom || params.dateTo
      ? {
          dueDate: {
            ...(params.dateFrom && { gte: new Date(params.dateFrom) }),
            ...(params.dateTo && { lte: new Date(params.dateTo) }),
          },
        }
      : {}),
  }

  const [data, total] = await Promise.all([
    db.maintenanceSchedule.findMany({
      where,
      include: {
        plan: {
          include: {
            type: { select: { id: true, name: true, code: true, color: true } },
          },
        },
        machine: { select: targetMachineSelect },
        asset: { select: targetAssetSelect },
      },
      orderBy: { dueDate: "asc" },
      skip: (params.page - 1) * params.pageSize,
      take: params.pageSize,
    }),
    db.maintenanceSchedule.count({ where }),
  ])

  return {
    data,
    total,
    page: params.page,
    pageSize: params.pageSize,
    totalPages: Math.ceil(total / params.pageSize),
  }
}

export async function createMaintenanceSchedule(
  db: PrismaClient,
  params: { companyId: string; roles: UserRole[]; userId?: string; input: CreateMaintenanceScheduleInput }
) {
  const plan = await db.maintenancePlan.findFirst({
    where: {
      id: params.input.planId,
      AND: [targetScopeWhere(params.companyId, "all")],
    },
    select: {
      isActive: true,
      frequencyUnit: true,
      machine: { select: targetMachineSelect },
      asset: { select: targetAssetSelect },
    },
  })

  if (!plan) {
    return { error: "Maintenance plan not found" as const, status: 404 as const }
  }
  const planBranchId = targetBranchId(plan)
  if (!planBranchId || !permissionCoversBranch(params.roles, "schedules", "create", planBranchId, false)) {
    return { error: "Forbidden" as const, status: 403 as const }
  }
  if (!plan.isActive || targetInactiveReason(plan) || plan.frequencyUnit === "runtime_hour") {
    return { error: "แผนนี้สร้างรอบไม่ได้" as const, status: 400 as const }
  }
  const dueDateOnly = parseDateOnly(params.input.dueDate)
  if (!dueDateOnly) {
    return { error: "Invalid due date" as const, status: 400 as const }
  }
  const exists = await db.maintenanceSchedule.findUnique({
    where: { planId_dueDate: { planId: params.input.planId, dueDate: dueDateOnly } },
    select: { id: true },
  })
  if (exists) return { error: "มีรอบของวันนี้อยู่แล้ว" as const, status: 409 as const }

  await db.$transaction(
    (tx) =>
      generatePmForPlan(tx, {
        planId: params.input.planId,
        today: new Date(),
        userId: params.userId ?? null,
        extraDueDates: [dueDateOnly],
      }),
    { timeout: 60_000 }
  )
  const schedule = await db.maintenanceSchedule.findUnique({
    where: { planId_dueDate: { planId: params.input.planId, dueDate: dueDateOnly } },
    include: { workOrder: { select: { id: true, woNumber: true } } },
  })

  return { data: schedule }
}

export async function deleteMaintenanceSchedule(
  db: PrismaClient,
  params: { id: string; companyId: string; roles: UserRole[]; userId: string; ipAddress?: string | null; userAgent?: string | null }
) {
  const schedule = await db.maintenanceSchedule.findFirst({
    where: { id: params.id, AND: [targetScopeWhere(params.companyId, "all")] },
    include: {
      workOrder: { select: { id: true } },
      machine: { select: { branchId: true } },
      asset: { select: { branchId: true } },
    },
  })

  if (!schedule) {
    return { error: "Not found" as const, status: 404 as const }
  }
  const scheduleBranchId = schedule.asset?.branchId ?? schedule.machine?.branchId
  if (!scheduleBranchId || !permissionCoversBranch(params.roles, "schedules", "delete", scheduleBranchId, false)) {
    return { error: "Forbidden" as const, status: 403 as const }
  }

  if (schedule.workOrder) {
    return {
      error: "Cannot delete schedule because it already has work orders",
      status: 400 as const,
    }
  }

  await db.$transaction([
    db.maintenanceSchedule.delete({ where: { id: params.id } }),
    db.auditLog.create({
      data: {
        userId: params.userId,
        tableName: "maintenance_schedules",
        recordId: params.id,
        action: "delete",
        oldValues: JSON.parse(JSON.stringify(schedule)),
        ipAddress: params.ipAddress ?? null,
        userAgent: params.userAgent ?? null,
      },
    }),
  ])

  return { success: true }
}

/** Cron ทั้งระบบ */
export async function generateMaintenanceSchedules(db: PrismaClient, params: { today?: Date } = {}) {
  const result = await generatePreventiveWork(db, { today: params.today })
  return { success: true, generated: result.schedulesCreated, ...result }
}

/** ปุ่มบนปฏิทิน: เฉพาะแผนในสาขาที่ผู้ใช้มีสิทธิ์ schedules:create */
export async function generateMaintenanceSchedulesForUser(
  db: PrismaClient,
  params: { companyId: string; roles: UserRole[]; userId: string; today?: Date }
) {
  const branches = await db.branch.findMany({
    where: { companyId: params.companyId, deletedAt: null },
    select: { id: true },
  })
  const branchIds = branches
    .map((b) => b.id)
    .filter((id) => permissionCoversBranch(params.roles, "schedules", "create", id, false))
  if (branchIds.length === 0) return { error: "Forbidden" as const, status: 403 as const }
  const result = await generatePreventiveWork(db, {
    today: params.today,
    companyId: params.companyId,
    branchIds,
    userId: params.userId,
  })
  return { data: result }
}
